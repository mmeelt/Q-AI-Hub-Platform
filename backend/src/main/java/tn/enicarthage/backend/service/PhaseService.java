package tn.enicarthage.backend.service;

import jakarta.persistence.EntityNotFoundException;
import lombok.RequiredArgsConstructor;
import lombok.extern.slf4j.Slf4j;
import org.springframework.stereotype.Service;
import org.springframework.transaction.annotation.Transactional;
import tn.enicarthage.backend.entity.Application;
import tn.enicarthage.backend.entity.Event;
import tn.enicarthage.backend.entity.Phase;
import tn.enicarthage.backend.entity.PhaseSubmission;
import tn.enicarthage.backend.repository.ApplicationRepository;
import tn.enicarthage.backend.repository.EventRepository;
import tn.enicarthage.backend.repository.PhaseRepository;

import java.util.List;
import java.util.Map;
import java.util.Optional;
import java.util.UUID;

@Service
@RequiredArgsConstructor
@Slf4j
public class PhaseService {

    private final PhaseRepository phaseRepository;
    private final EventRepository eventRepository;
    private final ApplicationRepository applicationRepository;
    private final NotificationService notificationService;
    private final tn.enicarthage.backend.repository.PhaseSubmissionRepository phaseSubmissionRepository;
    private final tn.enicarthage.backend.repository.PitchRoundRepository pitchRoundRepository;

    // ── CREATE ────────────────────────────────────────────────────

    @Transactional
    public Phase createPhase(String eventId, Phase phase) {
        Event event = eventRepository.findById(eventId)
                .orElseThrow(() -> new EntityNotFoundException("Event not found with id: " + eventId));

        if (phase.getPhaseName() == null || phase.getPhaseName().isBlank()) {
            throw new IllegalArgumentException("Phase name is required");
        }
        if (phase.getStartDate() != null && phase.getEndDate() != null
                && phase.getEndDate().isBefore(phase.getStartDate())) {
            throw new IllegalArgumentException("Phase end date must be after its start date");
        }

        List<Phase> existing = phaseRepository.findByEventIdOrderByPhaseOrderAsc(eventId);
        int nextOrder = existing.stream().mapToInt(Phase::getPhaseOrder).max().orElse(0) + 1;
        if (phase.getPhaseOrder() == null) {
            phase.setPhaseOrder(nextOrder);
        } else if (phase.getPhaseOrder() < 1) {
            throw new IllegalArgumentException("Phase order must be 1 or more");
        } else if (existing.stream().anyMatch(p -> p.getPhaseOrder().equals(phase.getPhaseOrder()))) {
            throw new IllegalStateException("Phase " + phase.getPhaseOrder() + " already exists for this event");
        }
        // A new phase cannot be slotted before a phase that has already started.
        boolean beforeStartedPhase = existing.stream().anyMatch(p -> p.getPhaseOrder() > phase.getPhaseOrder()
                && (Boolean.TRUE.equals(p.getPhaseActive()) || Boolean.TRUE.equals(p.getPhaseLocked())));
        if (beforeStartedPhase) {
            throw new IllegalStateException("A new phase must come after the phases that have already started");
        }

        phase.setEvent(event);
        // The id is not generated by the database, and the event comes from the URL, not the body
        phase.setPhaseId(UUID.randomUUID().toString());
        phase.setEventId(eventId);
        phase.setPhaseName(phase.getPhaseName().trim());
        if (phase.getPhaseType() == null) {
            phase.setPhaseType(Phase.PhaseType.QUESTIONNAIRE);
        }
        // A new phase always starts closed; the admin opens it with "Activate".
        phase.setPhaseActive(false);
        phase.setPhaseLocked(false);

        return phaseRepository.save(phase);
    }

    // ── READ ──────────────────────────────────────────────────────

    public Phase getPhaseById(String phaseId) {
        return phaseRepository.findById(phaseId)
                .orElseThrow(() -> new EntityNotFoundException("Phase not found with id: " + phaseId));
    }

    public List<Phase> getPhasesByEvent(String eventId) {
        // Keep historical data consistent: if a later phase is active, older phases must be locked.
        return reconcilePhaseProgress(eventId);
    }

    public Phase getActivePhase(String eventId) {
        reconcilePhaseProgress(eventId);
        return phaseRepository.findByEventIdAndPhaseActiveTrue(eventId)
                .orElseThrow(() -> new EntityNotFoundException("No active phase for event: " + eventId));
    }

    // ── UPDATE ────────────────────────────────────────────────────

    @Transactional
    public Phase updatePhase(String phaseId, Phase updatedPhase) {
        Phase existing = getPhaseById(phaseId);
        if (Boolean.TRUE.equals(existing.getPhaseLocked())) {
            throw new IllegalStateException("This phase is locked and can no longer be modified");
        }
        existing.setPhaseName(updatedPhase.getPhaseName());
        existing.setPhaseOrder(updatedPhase.getPhaseOrder());
        existing.setStartDate(updatedPhase.getStartDate());
        existing.setEndDate(updatedPhase.getEndDate());
        return phaseRepository.save(existing);
    }

    @Transactional
    public Phase updateFormFields(String phaseId, String formFieldsJson) {
        Phase phase = getPhaseById(phaseId);
        if (Boolean.TRUE.equals(phase.getPhaseLocked())) {
            throw new IllegalStateException("This phase is locked and questions can no longer be updated");
        }
        if (phase.getPhaseType() == Phase.PhaseType.PITCH) {
            throw new IllegalStateException("Pitch phases do not use form questions. Use rounds and criteria instead.");
        }
        phase.updateFormFields(formFieldsJson);
        return phaseRepository.save(phase);
    }

    @Transactional
    public Phase activatePhase(String phaseId) {
        Phase phase = getPhaseById(phaseId);
        if (Boolean.TRUE.equals(phase.getPhaseLocked())) {
            throw new IllegalStateException("This phase is locked forever and cannot be activated again");
        }

        // Phase 1 must have questions before participants can be invited to answer
        // (its own questions, or — for older events — the event's application questions).
        if (phase.getPhaseType() != Phase.PhaseType.PITCH && Integer.valueOf(1).equals(phase.getPhaseOrder())
                && !hasQuestions(phase.getFormFieldsJson())
                && !eventRepository.findById(phase.getEventId()).map(e -> hasQuestions(e.getFormFieldsJson())).orElse(false)) {
            throw new IllegalStateException("Add the Phase 1 questions (Edit Questions) before opening Phase 1");
        }

        // Deactivate all other phases; lock all earlier phases forever.
        String eventId = phase.getEventId();
        List<Phase> allPhases = reconcilePhaseProgress(eventId);

        // Never allow going backward: if any later phase is already active/locked, this phase is finished forever.
        boolean tryingToReopenFinishedPhase = allPhases.stream().anyMatch(p ->
                p.getPhaseOrder() > phase.getPhaseOrder()
                        && (Boolean.TRUE.equals(p.getPhaseActive()) || Boolean.TRUE.equals(p.getPhaseLocked())));
        if (tryingToReopenFinishedPhase) {
            throw new IllegalStateException("Cannot reactivate a previous phase after a later phase has started");
        }

        allPhases.forEach(p -> {
            p.setPhaseActive(false);
            if (p.getPhaseOrder() < phase.getPhaseOrder()) {
                p.setPhaseLocked(true);
            }
        });
        phaseRepository.saveAll(allPhases);

        // Activate this phase
        phase.activatePhase();
        Phase saved = phaseRepository.save(phase);

        // Opening a phase grants no acceptance. Notify only those who may take part.
        try {
            participantsOf(phase, allPhases)
                .forEach(app -> notificationService.createNotification(
                    app.getApplicantUserId(),
                    phase.getPhaseName() + " is now open",
                    phase.getPhaseType() == Phase.PhaseType.PITCH
                        ? "Phase " + phase.getPhaseOrder() + " (" + phase.getPhaseName() + ") has started."
                        : "Phase " + phase.getPhaseOrder() + " is now open. You can submit your answers.",
                    "PHASE_ACTIVATED",
                    "/dashboard?tab=applications"
                ));
        } catch (Exception e) {
            log.error("Failed to notify applicants on phase activation: {}", e.getMessage());
        }

        return saved;
    }

    /**
     * Who may take part in a phase: Phase 1 → the accepted applications;
     * Phase N → the participants accepted in Phase N-1.
     */
    private List<Application> participantsOf(Phase phase, List<Phase> allPhases) {
        Phase previous = phase.getPhaseOrder() != null && phase.getPhaseOrder() > 1
                ? allPhases.stream().filter(p -> p.getPhaseOrder() == phase.getPhaseOrder() - 1).findFirst().orElse(null)
                : null;
        return applicationRepository.findByTargetEventId(phase.getEventId()).stream()
                .filter(app -> "ACCEPTED".equalsIgnoreCase(app.getApplicationStatus()))
                .filter(app -> previous == null || phaseSubmissionRepository
                        .findByPhaseIdAndSourceApplicationId(previous.getPhaseId(), app.getApplicationId())
                        .map(s -> s.getOutcome() == PhaseSubmission.DecisionStatus.ACCEPTED)
                        .orElse(false))
                .toList();
    }

    private boolean hasSubmitted(Phase phase, Application app) {
        return phaseSubmissionRepository.findByPhaseIdAndSourceApplicationId(phase.getPhaseId(), app.getApplicationId())
                .map(s -> s.getStatus() != PhaseSubmission.SubmissionStatus.DRAFT)
                .orElse(false);
    }

    /**
     * What opening this phase would leave behind in the questionnaire phase open now (it closes for good):
     * participants who never submitted, and submissions still waiting for a decision. The admin is warned first.
     */
    public Map<String, Object> getActivationCheck(String phaseId) {
        Phase phase = getPhaseById(phaseId);
        List<Phase> allPhases = reconcilePhaseProgress(phase.getEventId());
        Optional<Phase> closing = allPhases.stream()
                .filter(p -> Boolean.TRUE.equals(p.getPhaseActive()) && p.getPhaseOrder() < phase.getPhaseOrder()
                        && p.getPhaseType() != Phase.PhaseType.PITCH)
                .findFirst();
        if (closing.isEmpty()) {
            return Map.of("closingPhaseName", "", "notSubmitted", 0L, "awaitingDecision", 0L);
        }
        List<Application> participants = participantsOf(closing.get(), allPhases);
        long notSubmitted = participants.stream().filter(app -> !hasSubmitted(closing.get(), app)).count();
        long awaitingDecision = participants.stream()
                .map(app -> phaseSubmissionRepository.findByPhaseIdAndSourceApplicationId(closing.get().getPhaseId(), app.getApplicationId()))
                .flatMap(Optional::stream)
                .filter(s -> s.getStatus() != PhaseSubmission.SubmissionStatus.DRAFT
                        && s.getOutcome() == PhaseSubmission.DecisionStatus.PENDING)
                .count();
        return Map.of("closingPhaseName", closing.get().getPhaseName(),
                "notSubmitted", notSubmitted, "awaitingDecision", awaitingDecision);
    }

    /**
     * Opens a finished phase again (e.g. the next phase was opened too early and some participants never answered).
     * The later phases go back to "not started"; their submissions and results are kept.
     */
    @Transactional
    public Phase reopenPhase(String phaseId) {
        Phase phase = getPhaseById(phaseId);
        List<Phase> allPhases = reconcilePhaseProgress(phase.getEventId());
        if (Boolean.TRUE.equals(phase.getPhaseActive())) {
            throw new IllegalStateException("This phase is already open");
        }
        if (!Boolean.TRUE.equals(phase.getPhaseLocked())) {
            throw new IllegalStateException("This phase has not started yet: use Activate");
        }

        allPhases.forEach(p -> {
            if (p.getPhaseOrder() > phase.getPhaseOrder()) {
                p.setPhaseActive(false);
                p.setPhaseLocked(false);
            }
        });
        phaseRepository.saveAll(allPhases);
        phase.setPhaseLocked(false);
        phase.activatePhase();
        Phase saved = phaseRepository.save(phase);

        // Tell the participants who have not answered yet that they can now do it
        try {
            participantsOf(phase, allPhases).stream()
                .filter(app -> phase.getPhaseType() == Phase.PhaseType.PITCH || !hasSubmitted(phase, app))
                .forEach(app -> notificationService.createNotification(
                    app.getApplicantUserId(),
                    phase.getPhaseName() + " is open again",
                    phase.getPhaseType() == Phase.PhaseType.PITCH
                        ? "Phase " + phase.getPhaseOrder() + " (" + phase.getPhaseName() + ") has been reopened."
                        : "Phase " + phase.getPhaseOrder() + " has been reopened. You can submit your answers.",
                    "PHASE_ACTIVATED",
                    "/dashboard?tab=applications"
                ));
        } catch (Exception e) {
            log.error("Failed to notify applicants on phase reopening: {}", e.getMessage());
        }
        return saved;
    }

    private boolean hasQuestions(String formFieldsJson) {
        if (formFieldsJson == null) return false;
        String trimmed = formFieldsJson.trim();
        return !trimmed.isEmpty() && !trimmed.equals("[]") && !trimmed.equals("null");
    }

    @Transactional
    public Phase deactivatePhase(String id) {
        Phase phase = getPhaseById(id);
        if (Boolean.TRUE.equals(phase.getPhaseLocked())) {
            throw new IllegalStateException("This phase is locked and cannot be deactivated");
        }
        phase.deactivatePhase();
        return phaseRepository.save(phase);
    }

    /**
     * Ends the open phase (e.g. the final pitch: no next phase will close it). It no longer accepts
     * anything; its submissions and results are kept and it can still be reopened.
     */
    @Transactional
    public Phase closePhase(String id) {
        Phase phase = getPhaseById(id);
        if (!Boolean.TRUE.equals(phase.getPhaseActive())) {
            throw new IllegalStateException("Only an open phase can be closed");
        }
        phase.lockPhase();
        return phaseRepository.save(phase);
    }

    // ── DELETE ────────────────────────────────────────────────────

    @Transactional
    public void deletePhase(String id) {
        Phase phase = getPhaseById(id);
        // Deleting would cascade to the students' work or break the pitch rounds: refuse with a clear reason
        if (Boolean.TRUE.equals(phase.getPhaseActive())) {
            throw new IllegalStateException("This phase is open: deactivate it before deleting it");
        }
        if (Boolean.TRUE.equals(phase.getPhaseLocked())) {
            throw new IllegalStateException("This phase is finished and keeps its results: it cannot be deleted");
        }
        if (!phaseSubmissionRepository.findByPhaseId(id).isEmpty()) {
            throw new IllegalStateException("Startups have already submitted to this phase: it cannot be deleted");
        }
        if (!pitchRoundRepository.findByPhaseIdOrderByRoundNumberAsc(id).isEmpty()) {
            throw new IllegalStateException("This phase has pitch rounds: delete them before deleting the phase");
        }
        phaseRepository.delete(phase);
    }

    // ── RESULTS ───────────────────────────────────────────────────

    public Map<String, Object> getPhaseResults(String id) {
        Phase phase = getPhaseById(id);
        return phase.calculatePhaseResults();
    }

    @Transactional
    protected List<Phase> reconcilePhaseProgress(String eventId) {
        List<Phase> phases = phaseRepository.findByEventIdOrderByPhaseOrderAsc(eventId);
        if (phases.isEmpty()) return phases;

        Integer highestActiveOrder = phases.stream()
                .filter(p -> Boolean.TRUE.equals(p.getPhaseActive()))
                .map(Phase::getPhaseOrder)
                .max(Integer::compareTo)
                .orElse(null);

        if (highestActiveOrder == null) return phases;

        boolean changed = false;
        for (Phase p : phases) {
            // Any phase before the active one is finished forever.
            if (p.getPhaseOrder() < highestActiveOrder) {
                if (!Boolean.TRUE.equals(p.getPhaseLocked())) {
                    p.setPhaseLocked(true);
                    changed = true;
                }
                if (Boolean.TRUE.equals(p.getPhaseActive())) {
                    p.setPhaseActive(false);
                    changed = true;
                }
            }
            // Ensure only one active phase remains.
            if (p.getPhaseOrder() > highestActiveOrder && Boolean.TRUE.equals(p.getPhaseActive())) {
                p.setPhaseActive(false);
                changed = true;
            }
        }

        if (changed) {
            phaseRepository.saveAll(phases);
        }
        return phases;
    }
}
